import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import path from "node:path";

// Optional QA utility. Use an existing Playwright installation; it is not a runtime dependency.
const modulePath = process.env.PLAYWRIGHT_MODULE;
const { chromium } = await import(modulePath ? pathToFileURL(path.resolve(modulePath)).href : "playwright");
const base = process.env.QA_BASE_URL || "http://localhost:5173";
const output = path.resolve("work/browser-qa");
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? { executablePath: process.env.BROWSER_EXECUTABLE_PATH } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", e => errors.push(e.message));
try {
 const response = await page.goto(base, { waitUntil: "networkidle" });
 assert.equal(response.status(), 200);
 await page.getByRole("heading", { name: /OAuth setup,/ }).waitFor();
 assert.equal(await page.locator(".guide-card").count(), 3);
 await page.screenshot({ path: path.join(output, "library-desktop.png"), fullPage: true });
 await page.getByRole("textbox", { name: "Search guide library" }).fill("gmail");
 assert.equal(await page.locator(".guide-card").count(), 1);
 await page.getByRole("button", { name: "Quick starts", exact: true }).click();
 await page.getByRole("heading", { name: "No matching guide yet" }).waitFor();
 await page.getByRole("textbox", { name: "Search guide library" }).fill("");
 assert.equal(await page.locator(".guide-card").count(), 1);
 await page.getByRole("button", { name: "All guides", exact: true }).click();
 await page.locator(".guide-card").filter({ hasText: "GitHub" }).click();
 await page.getByRole("heading", { name: "GitHub", exact: true }).waitFor();
 await page.getByRole("button", { name: /Complete step 1:/ }).click();
 await page.reload({ waitUntil: "networkidle" });
 await page.getByRole("button", { name: /Uncheck step 1:/ }).waitFor();
 await page.getByRole("tab", { name: "Blockers", exact: false }).click();
 await page.locator("summary").first().click();
 assert.equal(await page.locator("details[open]").count(), 1);
 await page.getByRole("tab", { name: "Evidence", exact: true }).click();
 await page.getByRole("heading", { name: "Evidence, with its limits" }).waitFor();
 await page.screenshot({ path: path.join(output, "github-evidence.png"), fullPage: true });
 const downloadPromise = page.waitForEvent("download");
 await page.getByRole("button", { name: "Export guide" }).click();
 const download = await downloadPromise;
 const downloadedPath = path.join(output, "github-guide.md");
 await download.saveAs(downloadedPath);
 const md = await readFile(downloadedPath, "utf8");
 assert.ok(md.includes("## Scopes") && md.includes("## Next action") && md.includes("## Blockers"));
 await page.getByRole("button", { name: "Share guide" }).click();
 await page.getByRole("status").waitFor();
 await page.goto(`${base}/?guide=gmail`, { waitUntil: "networkidle" });
 await page.getByRole("heading", { name: "Gmail", exact: true }).waitFor();
 assert.ok((await page.locator("main").innerText()).includes("restricted"));
 await page.screenshot({ path: path.join(output, "gmail-guide.png"), fullPage: true });
 await page.goto(`${base}/?guide=missing`, { waitUntil: "networkidle" });
 await page.getByRole("alert").waitFor();
 assert.ok((await page.getByRole("alert").innerText()).includes("Guide not found"));
 // Delayed saved-guide responses must not override a user's newer navigation.
 const fixtureId = "00000000-0000-4000-8000-000000000001";
 const seed = await (await page.request.get(`${base}/api/guides/github`)).json();
 await page.route(`**/api/guides/${fixtureId}`, async route => { await new Promise(r => setTimeout(r, 900)); try { await route.fulfill({ json: { ...seed, id: fixtureId, name: "Delayed test fixture", kind: "generated" } }); } catch {} });
 await page.goto(`${base}/?guide=${fixtureId}`, { waitUntil: "domcontentloaded" });
 await page.locator(".load-state").waitFor();
 await page.locator(".nav-item").first().click();
 await page.waitForTimeout(1200);
 await page.getByRole("heading", { name: /OAuth setup,/ }).waitFor();
 assert.equal(new URL(page.url()).search, "");
 await page.goto(base, { waitUntil: "networkidle" });
 await page.locator(".research-banner").getByRole("button", { name: "Investigate an app" }).click();
 await page.getByRole("dialog").waitFor();
 await page.getByLabel("App name or website").fill("Notion");
 await page.getByLabel("What should your integration do?").fill("Search a user's workspace pages from an AI assistant");
 if (process.env.QA_EXPECT_UNCONFIGURED === "1") {
  await page.getByRole("button", { name: "Generate my guide" }).click();
  await page.getByRole("alert").waitFor();
  assert.ok((await page.getByRole("alert").innerText()).includes("not configured"));
 }
 await page.screenshot({ path: path.join(output, "research-dialog.png"), fullPage: true });
 await page.getByRole("button", { name: "Close", exact: true }).click();
 await page.setViewportSize({ width: 390, height: 844 });
 await page.screenshot({ path: path.join(output, "library-mobile.png"), fullPage: true });
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile page overflows horizontally");
 await page.locator(".guide-card").filter({ hasText: "Slack" }).click();
 await page.getByRole("heading", { name: "Slack", exact: true }).waitFor();
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Mobile guide overflows horizontally");
 await page.screenshot({ path: path.join(output, "slack-mobile.png"), fullPage: true });
 assert.deepEqual(errors, []);
 console.log("PASS: library, filters/search, guide navigation, checklist persistence, blockers/evidence, Markdown export, share feedback, direct URLs, missing-guide error, research dialog, responsive overflow, no browser page errors.");
 console.log(`Screenshots: ${output}`);
 console.log("No successful live model call or provider OAuth connection is established by this suite.");
} finally { await browser.close(); }
